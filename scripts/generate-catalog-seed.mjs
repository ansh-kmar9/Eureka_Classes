// Builds supabase/migrations/0006_catalog_seed.sql from supabase/seed/catalog-data.mjs.
// Run: node scripts/generate-catalog-seed.mjs
import { writeFile } from "node:fs/promises";
import { CHAPTERS, listSubjects } from "../supabase/seed/catalog-data.mjs";

const q = (value) => `'${String(value).replace(/'/g, "''")}'`;

const subjects = listSubjects();
const subjectValues = subjects
  .map((s) => `  (${q(s.board)}, ${s.class}, ${s.stream ? q(s.stream) : "null"}, ${q(s.name)}, ${s.position})`)
  .join(",\n");

// Chapters apply to every subject row with the same board, class and name (all streams, both boards).
const topicRows = [];
for (const [key, chapters] of Object.entries(CHAPTERS)) {
  const [klass, subject] = key.split("|");
  for (const board of ["cbse", "bseb"]) {
    chapters.forEach((name, index) =>
      topicRows.push(`  (${q(board)}, ${klass}, ${q(subject)}, ${q(name)}, ${index + 1})`),
    );
  }
}

const sql = `-- Eureka Classes: starting subjects and chapters for the practice test series.
-- Generated by scripts/generate-catalog-seed.mjs from supabase/seed/catalog-data.mjs. Do not edit by hand.
-- Run in the Supabase SQL Editor after 0005. Safe to re-run: existing rows are left alone.

insert into public.catalog_subjects (board, class, stream, name, position)
select v.board::public.board_type, v.class, v.stream::public.stream_type, v.name, v.position
from (values
${subjectValues}
) as v(board, class, stream, name, position)
on conflict do nothing;

insert into public.catalog_topics (subject_id, name, position)
select s.id, v.name, v.position
from (values
${topicRows.join(",\n")}
) as v(board, class, subject, name, position)
join public.catalog_subjects s
  on s.board = v.board::public.board_type
 and s.class = v.class
 and lower(s.name) = lower(v.subject)
on conflict do nothing;
`;

await writeFile("supabase/migrations/0006_catalog_seed.sql", sql);
console.log(`Wrote ${subjects.length} subject rows and ${topicRows.length} chapter rows (before stream expansion).`);
